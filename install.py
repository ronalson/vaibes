#!/usr/bin/env python3
"""Install the vaibes agent setup into the home directory.

Usage: python3 install.py [--check] AGENT...

Copies the role rules, the Claude agent files, and agent-role, and writes the
global rules into a managed block in each agent's startup file. Every target is
checked before anything is written; if one is refused, nothing is written.
Uses only the standard library and reads nothing from the environment except
the home directory.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Tuple

REPO = Path(__file__).resolve().parent
AGENTS = ("claude", "codex", "grok", "pi")
STATE = ".config/vaibes/install-state.json"

BEGIN = "<!-- BEGIN vaibes rules: generated by vaibes install.py; edit rules/ in the vaibes repository -->"
END = "<!-- END vaibes rules -->"
# Marker lines are matched by prefix so an edited or older BEGIN line still
# counts when checking the layout.
BEGIN_PREFIX = "<!-- BEGIN vaibes rules"
END_PREFIX = "<!-- END vaibes rules"

# Startup files that get the rules block, and whether they include delegation.
RULES_TARGETS = {
    "claude": (".claude/CLAUDE.md", True),
    "codex": (".codex/AGENTS.md", True),
    "grok": (".grok/AGENTS.md", True),
    "pi": (".pi/agent/AGENTS.md", False),
}

REFUSED = ("symlink", "changed locally", "bad markers")


class BadMarkers(Exception):
    pass


@dataclass
class Target:
    rel: str  # path relative to the home directory
    content: str  # the whole file, or the block contents for a managed block
    block: bool = False
    mode: Optional[int] = None


@dataclass
class Plan:
    target: Target
    status: str  # ok, missing, outdated, changed locally, symlink, bad markers
    reason: str = ""
    new: Optional[str] = None  # the whole new file, when it can be written


def read_source(rel: str) -> str:
    return (REPO / rel).read_bytes().decode("utf-8")


def build_targets(agents: List[str]) -> List[Target]:
    targets = [
        Target(".local/bin/agent-role", read_source("bin/agent-role"), mode=0o755),
        Target(".config/agent-roles/scout.md", read_source("roles/scout.md")),
        Target(".config/agent-roles/reviewer.md", read_source("roles/reviewer.md")),
    ]
    if "claude" in agents:
        targets += [
            Target(".claude/agents/scout.md", read_source("claude-agents/scout.md")),
            Target(".claude/agents/worker.md", read_source("claude-agents/worker.md")),
        ]
    shared = ensure_newline(read_source("rules/global.md"))
    delegation = ensure_newline(read_source("rules/delegation.md"))
    for agent in AGENTS:
        if agent in agents:
            rel, with_delegation = RULES_TARGETS[agent]
            rules = shared + "\n" + delegation if with_delegation else shared
            targets.append(Target(rel, rules, block=True))
    return targets


def ensure_newline(text: str) -> str:
    return text if text.endswith("\n") else text + "\n"


def sha256(text: str) -> str:
    return hashlib.sha256(encode(text)).hexdigest()


def encode(text: str) -> bytes:
    return text.encode("utf-8", "surrogateescape")


def decode(data: bytes) -> str:
    # surrogateescape keeps any byte sequence round-trippable, so text outside
    # the block is written back exactly as it was read.
    return data.decode("utf-8", "surrogateescape")


def split_block(text: str) -> Optional[Tuple[str, str, str]]:
    """Return (before, contents, after) around the block, or None without markers."""
    lines = text.splitlines(keepends=True)
    begins = [i for i, line in enumerate(lines) if line.lstrip().startswith(BEGIN_PREFIX)]
    ends = [i for i, line in enumerate(lines) if line.lstrip().startswith(END_PREFIX)]
    if not begins and not ends:
        return None
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        raise BadMarkers
    b, e = begins[0], ends[0]
    return "".join(lines[:b]), "".join(lines[b + 1 : e]), "".join(lines[e + 1 :])


def render_block(contents: str) -> str:
    return f"{BEGIN}\n{contents}{END}\n"


def with_block(current: Optional[str], contents: str) -> str:
    """Return the file with its block set to contents. Text outside the block is kept."""
    if not current:
        return render_block(contents)
    parts = split_block(current)
    if parts is None:
        separator = "\n" if current.endswith("\n") else "\n\n"
        return current + separator + render_block(contents)
    before, _, after = parts
    return before + render_block(contents) + after


def symlink_in_path(home: Path, path: Path) -> bool:
    """True when the target or any folder between it and home is a symlink.

    A stow-folded folder makes the file look regular while writes land in the
    repository the link points to.
    """
    while path != home and path != path.parent:
        if path.is_symlink():
            return True
        path = path.parent
    return False


def classify(home: Path, target: Target, recorded: Optional[str]) -> Plan:
    path = home / target.rel
    if symlink_in_path(home, path):
        return Plan(target, "symlink", "is a symlink or inside a symlinked folder; unstow the dotfiles `agents` package first")
    not_ours = "exists but was not installed by vaibes" if recorded is None else "was changed since the last install"

    if not path.exists():
        new = render_block(target.content) if target.block else target.content
        return Plan(target, "missing", new=new)
    if not path.is_file():
        return Plan(target, "changed locally", "is not a regular file")
    current = decode(path.read_bytes())

    if target.block:
        try:
            parts = split_block(current)
        except BadMarkers:
            return Plan(target, "bad markers", "has malformed vaibes markers; fix or remove them by hand")
        new = with_block(current, target.content)
        if parts is None:
            return Plan(target, "missing", new=new)
        existing = parts[1]
        if existing == target.content:
            return Plan(target, "ok")
        if sha256(existing) == recorded:
            return Plan(target, "outdated", new=new)
        return Plan(target, "changed locally", "block " + not_ours)

    if current == target.content:
        if target.mode is not None and path.stat().st_mode & 0o777 != target.mode:
            return Plan(target, "outdated", new=current)
        return Plan(target, "ok")
    if sha256(current) == recorded:
        return Plan(target, "outdated", new=target.content)
    return Plan(target, "changed locally", not_ours)


def write_atomic(path: Path, data: bytes, mode: Optional[int]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if mode is None:
        mode = path.stat().st_mode & 0o777 if path.exists() else 0o644
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def load_state(home: Path) -> Dict[str, str]:
    path = home / STATE
    if not path.exists():
        return {}
    try:
        hashes = json.loads(path.read_text(encoding="utf-8"))["hashes"]
    except (ValueError, KeyError, TypeError) as error:
        raise ValueError(f"cannot read ~/{STATE}: {error}") from None
    if not isinstance(hashes, dict):
        raise ValueError(f"cannot read ~/{STATE}: hashes is not an object")
    return hashes


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="install.py",
        description="Install the vaibes agent rules, role files, Claude agent files, and agent-role.",
    )
    parser.add_argument("--check", action="store_true", help="report each target's status and write nothing")
    parser.add_argument("agents", nargs="+", metavar="AGENT", choices=AGENTS, help="one or more of: " + ", ".join(AGENTS))
    args = parser.parse_args(argv)

    home = Path.home()
    try:
        state = load_state(home)
    except ValueError as error:
        print(f"install.py: {error}", file=sys.stderr)
        return 1

    # Check every target before writing anything.
    plans = [classify(home, t, state.get(t.rel)) for t in build_targets(args.agents)]

    if args.check:
        for plan in plans:
            print(f"{plan.status:<16} ~/{plan.target.rel}")
        return 0 if all(plan.status == "ok" for plan in plans) else 1

    refused = [plan for plan in plans if plan.status in REFUSED]
    if refused:
        for plan in refused:
            print(f"refused: ~/{plan.target.rel} {plan.reason}", file=sys.stderr)
        print("install.py: nothing written", file=sys.stderr)
        return 1

    new_state = dict(state)
    for plan in plans:
        target = plan.target
        if plan.new is not None:
            write_atomic(home / target.rel, encode(plan.new), target.mode)
            print(f"wrote     ~/{target.rel}")
        else:
            print(f"unchanged ~/{target.rel}")
        new_state[target.rel] = sha256(target.content)

    if new_state != state:
        data = json.dumps({"hashes": new_state}, indent=2, sort_keys=True) + "\n"
        write_atomic(home / STATE, data.encode("utf-8"), None)
    return 0


if __name__ == "__main__":
    sys.exit(main())
